// t helper function to easily resolve translation keys based on active state
export const t = (key: keyof typeof translations['en'] | string, lang: LangType): any => {
  const dictionary = translations[lang] || translations['en'];
  const value = (dictionary as any)[key];
  if (value !== undefined) return value;
  // Fallback to English
  return (translations['en'] as any)[key] || key;
};
